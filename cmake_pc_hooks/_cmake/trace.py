"""Detect the files generated by CMake using its trace log."""

from __future__ import annotations

import json
import logging
import re
from pathlib import Path

log = logging.getLogger(__name__)


def parse_cache_variables(output: str) -> dict[str, str]:
    """Read the CMake cache variables from the output of `cmake -N -LA`."""
    variables = {}
    for line in output.splitlines():
        cmake_var = re.match(r'^(\w+):(BOOL|FILEPATH|PATH|STRING|INTERNAL)=(.*)$', line)
        if cmake_var:
            variables[cmake_var.group(1)] = cmake_var.group(3)
    return variables


def find_configured_files(
    trace_log: Path, source_dir: Path, build_dir: Path, cache_variables: dict[str, str]
) -> list[str]:
    """
    List the files generated by calls to `configure_file()` found in a CMake trace log.

    Only the calls made from a CMake file located inside the source directory are considered, except for those made
    from within FETCHCONTENT_BASE_DIR (if defined).
    """
    fetchcontent_dir = cache_variables.get('FETCHCONTENT_BASE_DIR')

    def _is_relevant(call: dict) -> bool:
        if call.get('cmd', '') != 'configure_file':
            return False
        if fetchcontent_dir is not None and fetchcontent_dir in call['file']:
            return False
        return source_dir.as_posix() in call['file']

    with trace_log.open(encoding='utf-8') as fd:
        calls = [json.loads(line) for line in fd.readlines()]

    configured_files = []
    for call in filter(_is_relevant, calls):
        input_file, configured_file = (Path(arg) for arg in call['args'][:2])
        if not configured_file.is_absolute():
            configured_file = build_dir / configured_file
        log.debug('detected call to configure_file(%s %s [...])', input_file, configured_file)
        configured_files.append(str(configured_file))
    return configured_files
